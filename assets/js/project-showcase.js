function renderCaseStudy(caseStudy) {
  if (!projectCaseStudyBody || !caseStudy) return;
  const make = (tag, className, text) => {
    const el = document.createElement(tag);
    if (className) el.className = className;
    if (text) el.textContent = text;
    return el;
  };
  const row = (label, content) => {
    const wrap = make("div", "case-study-row");
    wrap.append(make("dt", "", label));
    const dd = make("dd");
    dd.append(content);
    wrap.append(dd);
    return wrap;
  };
  const list = (items, className) => {
    const ul = make("ul", className);
    items.forEach((item) => ul.append(make("li", "", item)));
    return ul;
  };
  const dl = make("dl", "case-study-list");
  dl.append(
    row("Problem", make("p", "", caseStudy.problem)),
    row("Approach", list(caseStudy.approach, "case-study-points")),
    row("Stack", list(caseStudy.stack, "case-study-stack")),
    row("What I learned", make("p", "", caseStudy.learned)),
  );
  projectCaseStudyBody.replaceChildren(dl);
}

/* Read more: the detail description clamps to two lines. The toggle only
   shows when the text really overflows, and selectProject() resets it. */
const readMore = (() => {
  const text = projectDetailDescription;
  const toggle = document.getElementById("project-detail-toggle");
  const label = toggle?.querySelector(".readmore-label");
  if (!text || !toggle || !label) return { reset() {} };
  const LINES = 2;
  let expanded = false;

  function apply(animate) {
    if (!animate) text.classList.add("readmore-instant");
    const limit = parseFloat(getComputedStyle(text).lineHeight) * LINES;
    const full = text.scrollHeight;
    const overflows = full > limit + 2;
    if (!overflows) expanded = false;
    toggle.hidden = !overflows;
    text.classList.toggle("is-clamped", overflows && !expanded);
    text.style.maxHeight = overflows ? `${expanded ? full : limit}px` : "";
    toggle.setAttribute("aria-expanded", String(expanded));
    label.textContent = expanded ? "Show less" : "Read more…";
    if (!animate) {
      void text.offsetHeight; // commit the jump before transitions come back
      text.classList.remove("readmore-instant");
    }
  }

  toggle.addEventListener("click", () => {
    expanded = !expanded;
    apply(true);
  });

  let lastWidth = 0;
  new ResizeObserver(() => {
    if (text.clientWidth === lastWidth) return;
    lastWidth = text.clientWidth;
    apply(false);
  }).observe(text);
  document.fonts?.ready.then(() => apply(false));

  return {
    reset() {
      expanded = false;
      apply(false);
    },
  };
})();

/* Projects are picked only by clicking or tapping a card in the stack; scrolling
   the page never changes the selection. */
function selectProject(key) {
  const project = projects[key];
  if (!project) return;

  if (projectStage) {
    projectStage.style.setProperty("--project-accent", project.accent);
  }
  projectSpiral?.querySelectorAll(".infinite-spiral__item").forEach((item) => {
    item.classList.toggle("is-selected", item.dataset.project === key);
  });
  projectSpiral?.dispatchEvent(new CustomEvent("projectselect"));

  if (projectDetailImage) {
    projectDetailImage.src = `${project.images.light}.webp`;
    projectDetailImage.alt = project.imageAlt.light;
    // replay the fade-in for each newly picked project
    projectDetailImage.style.animation = "none";
    void projectDetailImage.offsetWidth;
    projectDetailImage.style.animation = "";
  }
  if (projectDetailCount) {
    const keys = Object.keys(projects);
    const pad = (n) => String(n).padStart(2, "0");
    projectDetailCount.textContent = `${pad(keys.indexOf(key) + 1)} / ${pad(keys.length)}`;
  }
  projectDetailType.textContent = project.type;
  projectDetailTitle.textContent = project.title;
  projectDetailDescription.textContent = project.description;
  readMore.reset();
  projectDetailLink.href = project.url;
  /* optional extra links: only projects that set them show these buttons */
  [
    [projectDetailDemo, project.demo],
    [projectDetailRepo, project.repo],
  ].forEach(([link, href]) => {
    if (!link) return;
    link.hidden = !href;
    if (href) link.href = href;
  });
  if (projectDetailRepo && project.repo) {
    const label = `${project.title} source code on GitHub`;
    projectDetailRepo.setAttribute("aria-label", label);
    projectDetailRepo.dataset.tip = label;
  }
  projectDetailLink.dataset.tip = `Open the ${project.title} live site`;
  if (projectDetailDemo && project.demo) {
    projectDetailDemo.dataset.tip = `Try the ${project.title} guest demo, no sign-up needed`;
  }
  renderCaseStudy(project.caseStudy);
}

function initializeProjectSpiral() {
  if (!projectSpiral) return;

  const settings = {
    speed: 0.55,
    radius: 170,
    cardWidth: 160,
    cardHeight: 116,
    verticalSpacing: 60,
    perspective: 1000,
    cardsPerTurn: 7,
    edgeFade: 0.3,
    edgeBlur: 6,
    centerScale: 1.2,
    grayscale: 1,
  };
  const projectKeys = Object.keys(projects);
  const spiralItems = [];

  projectSpiral.style.setProperty(
    "--spiral-card-width",
    `${settings.cardWidth}px`,
  );
  projectSpiral.style.setProperty(
    "--spiral-card-height",
    `${settings.cardHeight}px`,
  );
  projectSpiral.style.setProperty("--spiral-card-radius", "10px");
  projectSpiral.style.perspective = `${settings.perspective}px`;

  projectKeys.concat(projectKeys, projectKeys).forEach((projectKey) => {
    const project = projects[projectKey];
    const item = document.createElement("div");
    const button = document.createElement("button");
    const label = document.createElement("span");

    item.className = "infinite-spiral__item";
    item.dataset.project = projectKey;
    item.setAttribute("role", "listitem");
    button.className = "infinite-spiral__button";
    button.type = "button";
    button.setAttribute("aria-label", `Select ${project.title} project`);
    // Two stacked screenshots: the dark one sits underneath and the light
    // one fades in on top when the card is at the front or selected.
    const images = ["dark", "light"].map((mode) =>
      createSpiralImage(project, mode),
    );
    label.className = "infinite-spiral__label";
    label.textContent = project.title;

    button.append(...images, label);
    item.append(button);
    projectSpiral.append(item);
    spiralItems.push(item);
  });

  // Warm the cache for every variant so a swap never shows a blank card.
  projectKeys.forEach((projectKey) => {
    Object.values(projects[projectKey].images).forEach((base) => {
      const preload = new Image();
      preload.decoding = "async";
      preload.src = `${base}.webp`;
    });
  });

  function createSpiralImage(project, mode) {
    const image = document.createElement("img");
    const base = project.images[mode];
    image.className = `infinite-spiral__image infinite-spiral__image--${mode}`;
    image.src = `${base}.webp`;
    image.width = settings.cardWidth;
    image.height = settings.cardHeight;
    image.decoding = "async";
    image.addEventListener(
      "error",
      () => {
        if (!image.src.endsWith(".jpg")) image.src = `${base}.jpg`;
      },
      { once: true },
    );
    image.alt = project.imageAlt[mode];
    image.draggable = false;
    image.style.filter = `grayscale(${settings.grayscale})`;
    return image;
  }

  let frontItem = null;
  let pickedItem = null;
  let progress = 0;
  let previousTime = performance.now();
  let visible = true;
  let paused = false;
  // After a pick, ease the clicked card to the front and hold it there a while.
  let targetProgress = null;
  let holdUntil = 0;
  const PICK_HOLD_MS = 8000;
  let frameId;
  const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");
  const resizeObserver = new ResizeObserver(layoutSpiral);
  resizeObserver.observe(projectSpiral);
  const intersectionObserver = new IntersectionObserver(([entry]) => {
    visible = entry.isIntersecting;
  });
  intersectionObserver.observe(projectSpiral);

  function layoutSpiral() {
    const bounds = projectSpiral.getBoundingClientRect();
    const fit = Math.min(
      1,
      bounds.width / (settings.cardWidth * 2.8),
      bounds.height / (settings.cardHeight * 2.35),
    );
    const radius =
      Math.min(settings.radius, Math.max(72, bounds.width * 0.36)) * fit;
    const fadeStart = Math.min(Math.max(1 - settings.edgeFade, 0), 0.98);
    const half = spiralItems.length / 2;
    let nearestItem = null;
    let nearestOffset = Infinity;
    let nearestSelected = null;
    let nearestSelectedOffset = Infinity;

    spiralItems.forEach((item, index) => {
      let offset = index - progress;
      offset =
        ((((offset + half) % spiralItems.length) + spiralItems.length) %
          spiralItems.length) -
        half;

      const edge = Math.min(Math.abs(offset) / Math.max(half, 1), 1);
      const opacity = 1 - smoothstep(fadeStart, 1, edge);
      const focus =
        1 - Math.min(Math.abs(offset) / (settings.cardsPerTurn * 0.65), 1);
      const scale = (1 + (settings.centerScale - 1) * focus) * fit;
      const angle = offset * (360 / settings.cardsPerTurn);
      const radians = (angle * Math.PI) / 180;
      const x = Math.sin(radians) * radius;
      const z = Math.cos(radians) * radius;
      const depthScale = Math.min(
        Math.max(settings.perspective / (settings.perspective - z), 0.72),
        1.45,
      );
      const depth = (z / Math.max(radius, 1) + 1) / 2;
      const blur = settings.edgeBlur * smoothstep(0.35, 1, edge);

      item.style.transform = `translate(-50%, -50%) translate3d(${x}px, ${offset * settings.verticalSpacing * fit}px, 0) scale(${scale * depthScale})`;
      item.style.opacity = opacity.toFixed(3);
      item.style.filter = blur > 0.01 ? `blur(${blur.toFixed(2)}px)` : "none";
      item.style.zIndex = String(Math.round(depth * 1000) + index);
      item.style.pointerEvents = opacity > 0.25 ? "auto" : "none";
      if (Math.abs(offset) < nearestOffset) {
        nearestOffset = Math.abs(offset);
        nearestItem = item;
      }
      if (
        item.classList.contains("is-selected") &&
        Math.abs(offset) < nearestSelectedOffset
      ) {
        nearestSelectedOffset = Math.abs(offset);
        nearestSelected = item;
      }
    });

    // The card nearest the front shows its light screenshot; only touch the
    // DOM when the front card actually changes.
    if (nearestItem !== frontItem) {
      frontItem?.classList.remove("is-front");
      nearestItem?.classList.add("is-front");
      frontItem = nearestItem;
    }

    // The selected project also shows light on one copy: the card that was
    // clicked, or (for tab/keyboard selection) the copy nearest the front.
    if (!pickedItem?.classList.contains("is-selected")) {
      setPickedItem(nearestSelected);
    }
  }

  function setPickedItem(item) {
    if (item === pickedItem) return;
    pickedItem?.classList.remove("is-picked");
    item?.classList.add("is-picked");
    pickedItem = item;
  }

  function smoothstep(min, max, value) {
    const amount = Math.min(Math.max((value - min) / (max - min || 1), 0), 1);
    return amount * amount * (3 - 2 * amount);
  }

  function animate(time) {
    const delta = Math.min((time - previousTime) / 1000, 0.05);
    previousTime = time;
    if (targetProgress !== null) {
      const remaining = targetProgress - progress;
      if (Math.abs(remaining) < 0.002) {
        progress =
          ((targetProgress % spiralItems.length) + spiralItems.length) %
          spiralItems.length;
        targetProgress = null;
      } else {
        progress += remaining * Math.min(1, delta * 7);
      }
    } else if (visible && !paused && time > holdUntil && !reducedMotion.matches) {
      progress = (progress + settings.speed * delta) % spiralItems.length;
    }
    layoutSpiral();
    if (!reducedMotion.matches) frameId = requestAnimationFrame(animate);
  }

  projectSpiral.addEventListener("pointerenter", () => {
    paused = true;
  });
  projectSpiral.addEventListener("pointerleave", () => {
    paused = false;
  });
  projectSpiral.addEventListener("focusin", () => {
    paused = true;
  });
  projectSpiral.addEventListener("focusout", (event) => {
    if (!projectSpiral.contains(event.relatedTarget)) paused = false;
  });
  projectSpiral.addEventListener("click", (event) => {
    const item = event.target.closest(".infinite-spiral__item");
    if (!item) return;
    setPickedItem(item);
    bringToFront(item);
    selectProject(item.dataset.project);
  });

  function bringToFront(item) {
    const count = spiralItems.length;
    const half = count / 2;
    const offset =
      ((((spiralItems.indexOf(item) - progress + half) % count) + count) %
        count) -
      half;
    holdUntil = performance.now() + PICK_HOLD_MS;
    if (reducedMotion.matches) {
      progress = (((progress + offset) % count) + count) % count;
      layoutSpiral();
    } else {
      targetProgress = progress + offset;
    }
  }

  // Re-run layout on selection so the picked card updates even when the
  // spiral is not animating (reduced motion).
  projectSpiral.addEventListener("projectselect", layoutSpiral);

  layoutSpiral();
  if (!reducedMotion.matches) frameId = requestAnimationFrame(animate);
  return () => {
    cancelAnimationFrame(frameId);
    resizeObserver.disconnect();
    intersectionObserver.disconnect();
    projectSpiral.removeEventListener("projectselect", layoutSpiral);
  };
}

